export const home = () => process.env.HOME || homedir();

// ---------- finding repos on disk ----------

const SCAN = ["code", "Code", "Repo", "repos", "projects", "Projects", "Developer", "src", "work", "dev"];
/** Folders that hold installed dependencies or build output, never a person's own clone. */
const SKIP = new Set(["node_modules", "vendor", "venv", "env", "target", "dist", "build", "Pods", "__pycache__", "bower_components", "site-packages"]);

/** Where to look for clones: the usual code folders, plus HOUSTON_SCAN_DIRS (colon-separated). */
export function scanDirs(): string[] {
  const extra = (process.env.HOUSTON_SCAN_DIRS ?? "").split(":").filter(Boolean);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const dir of [...SCAN.map((d) => join(home(), d)), ...extra]) {
    if (!existsSync(dir)) continue;
    const real = realpathSync.native(dir); // ~/code and ~/Code are the same folder on macOS
    if (!seen.has(real)) seen.add(real), out.push(dir);
  }
  return out;
}

/** owner/name from a GitHub remote URL (https or ssh), or undefined. */
export function repoFromUrl(url: string): string | undefined {
  return /github\.com[:/]+([\w.-]+\/[\w.-]+?)(?:\.git)?\/?$/.exec(url.trim())?.[1];
}

export function originOf(dir: string): string | undefined {
  const r = sh(["git", "-C", dir, "remote", "get-url", "origin"]);
  return r.ok ? repoFromUrl(r.stdout) : undefined;
}

/**
 * Finds local clones of `wanted` repos (case-insensitive), up to 3 levels under each scan folder.
 * Only main checkouts count (a `.git` folder): worktrees have a `.git` file and are read by collect
 * through their main checkout. The first clone found wins.
 */
export function findRepos(wanted: string[], dirs = scanDirs()): Record<string, string> {
  const byLower = new Map(wanted.map((r) => [r.toLowerCase(), r]));
  const found: Record<string, string> = {};
  const walk = (dir: string, depth: number) => {
    let names: string[];
    try {
      names = readdirSync(dir);
    } catch {
      return;
    }
    if (names.includes(".git") && statSync(join(dir, ".git")).isDirectory()) {
      const repo = byLower.get(originOf(dir)?.toLowerCase() ?? "");
      if (repo && !found[repo]) found[repo] = dir;
      return;
    }
    if (depth === 3) return;
    for (const n of names) {
      if (n.startsWith(".") || SKIP.has(n)) continue;
      const p = join(dir, n);
      try {
        if (statSync(p).isDirectory()) walk(p, depth + 1);
      } catch {}
    }
  };
  for (const d of dirs) walk(d, 0);
  return found;
}

/** The repo's `.git/info/exclude` (shared by its worktrees). */
export function excludeFile(repoDir: string): string {
  return sh(["git", "-C", repoDir, "rev-parse", "--path-format=absolute", "--git-path", "info/exclude"]).stdout || join(repoDir, ".git/info/exclude");
}

