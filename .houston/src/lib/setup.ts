// ---------- the global instruction block ----------

export const BLOCK_BEGIN = "<!-- houston:begin -->";
export const BLOCK_END = "<!-- houston:end -->";
export const globalFile = () => join(home(), ".claude", "CLAUDE.md");

/**
 * The block for ~/.claude/CLAUDE.md. It names no Houston repo itself: each folder's `.houston` file
 * says which one, so someone on two teams gets the right team in each folder from one block.
 */
export function globalBlock(): string {
  return `${BLOCK_BEGIN}
## Houston
If the folder you're working in has a \`.houston\` file at its root, it belongs to a team that uses Houston. The file's \`houston:\` line is the path of the team's Houston repo on this machine; below, \`<houston>\` means that path.
- Read \`<houston>/AGENTS.md\` for the team's context.
- At the start of a session, run \`<houston>/.houston/bin/houston run --if-due --quiet\` in the background and mention any message it prints.
- When you finish a meaningful piece of work, make a decision or get blocked, append one line to \`.houston-inbox.md\` in that folder: \`- HH:MM what happened (owner/repo#123 if you know it)\`. Plain words, one line, no secrets. Leave out work on Houston itself (setup, schedules, runs). Don't read the file back or summarise it.
In folders without a \`.houston\` file, ignore this section.
${BLOCK_END}`;
}

/** Replaces the block between the markers (or appends it), or removes it when `block` is null. Text outside the markers is kept as is. */
export function withBlock(text: string, block: string | null): string {
  const start = text.indexOf(BLOCK_BEGIN);
  const end = text.indexOf(BLOCK_END, start);
  if (start >= 0 && end >= 0) {
    const before = text.slice(0, start);
    const after = text.slice(end + BLOCK_END.length);
    if (block) return before + block + after;
    const rest = [before.replace(/\s+$/, ""), after.replace(/^\s+/, "")].filter(Boolean).join("\n\n");
    return rest ? rest.replace(/\n*$/, "\n") : "";
  }
  if (!block) return text;
  return text.trim() ? `${text.replace(/\n*$/, "")}\n\n${block}\n` : `${block}\n`;
}

// ---------- skills ----------

export function skillPath(name: string): { path: string; overridden: boolean } | undefined {
  const team = join(paths.teamSkills, name, "SKILL.md");
  if (existsSync(team)) return { path: team, overridden: existsSync(join(paths.coreSkills, name, "SKILL.md")) };
  const core = join(paths.coreSkills, name, "SKILL.md");
  return existsSync(core) ? { path: core, overridden: false } : undefined;
}

export function skillNames(): string[] {
  const names = (dir: string) => (existsSync(dir) ? readdirSync(dir).filter((n) => existsSync(join(dir, n, "SKILL.md"))) : []);
  return [...new Set([...names(paths.coreSkills), ...names(paths.teamSkills)])].sort();
}

// ---------- schedules in words and suggested run times ----------

const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

/** [1,2,3,4,5] → "Mon–Fri", [1,4] → "Mon, Thu", all → "every day". */
export function daysInWords(days: number[]): string {
  if (days.length === 7) return "every day";
  const runs: number[][] = [];
  for (const d of [...days].sort()) {
    const last = runs.at(-1);
    if (last && d === last.at(-1)! + 1) last.push(d);
    else runs.push([d]);
  }
  return runs.map((r) => (r.length > 2 ? `${DAYS[r[0]]}–${DAYS[r.at(-1)!]}` : r.map((d) => DAYS[d]).join(", "))).join(", ");
}

export type SuggestedRun = { time: string; days: number[]; why: string[] };

// ponytail: a fixed 09:00–18:00 working day; make it a personal setting if people ask for other hours.
const WORKDAY = { start: 9 * 60, end: 18 * 60 };
const hhmm = (m: number) => `${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`;

/**
 * When to run `houston run`, in the person's timezone: about an hour before each cadence (so the
 * draft is ready to review), at its publish deadline (so an untouched draft goes out on time), and
 * every `runs.every` through the working day on the days any cadence happens.
 */
export function suggestRuns(cadences: Cadence[], team: Pick<Team, "runs" | "rules">): SuggestedRun[] {
  const runs = new Map<string, SuggestedRun>(); // key: minute of day + day, merged below
  const add = (minute: number, day: number, why: string) => {
    const shift = minute < 0 ? -1 : 0; // an hour before 00:30 is the evening before
    const m = (minute + 1440) % 1440;
    const d = (day + shift + 7) % 7;
    const key = `${m}`;
    const r = runs.get(key) ?? { time: hhmm(m), days: [], why: [] };
    if (!r.days.includes(d)) r.days.push(d);
    if (!r.why.includes(why)) r.why.push(why);
    runs.set(key, r);
  };
  const deadline = team.rules.publish_runs === "review_until_deadline" ? parseDuration(team.rules.publish_deadline) / 60_000 : undefined;
  const allDays = new Set<number>();
  for (const c of cadences) {
    const [h, m] = c.schedule.time.split(":").map(Number);
    const at = h * 60 + m;
    for (const d of c.schedule.days) {
      allDays.add(d);
      add(at - 60, d, `an hour before ${c.title}`);
      if (deadline) add(at - deadline, d, `${c.title} publish deadline`);
    }
  }
  const every = Math.max(30, parseDuration(team.runs.every) / 60_000);
  for (let m = WORKDAY.start; m <= WORKDAY.end; m += every) for (const d of allDays) add(m, d, `every ${team.runs.every} during the working day`);
  return [...runs.values()].map((r) => ({ ...r, days: r.days.sort() })).sort((a, b) => a.time.localeCompare(b.time));
}

/** crontab lines for the suggested runs, one per minute-and-days group. */
export function cronLines(suggested: SuggestedRun[], command: string): string[] {
  const groups = new Map<string, { minute: string; hours: number[]; days: number[] }>();
  for (const r of suggested) {
    const [h, m] = r.time.split(":").map(Number);
    const key = `${m}|${r.days.join(",")}`;
    const g = groups.get(key) ?? { minute: String(m), hours: [], days: r.days };
    g.hours.push(h);
    groups.set(key, g);
  }
  return [...groups.values()].map((g) => `${g.minute} ${g.hours.join(",")} * * ${g.days.join(",")} ${command}`);
}

